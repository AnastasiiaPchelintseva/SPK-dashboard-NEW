-- Базовая схема: платформа (PLATFORM.md, раздел 10) и данные дашборда.
-- Время — UTC, строкой ISO 8601.

CREATE TABLE users (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    yandex_id       TEXT UNIQUE,              -- пусто до первого входа
    username        TEXT NOT NULL UNIQUE,
    email           TEXT NOT NULL DEFAULT '',
    display_name    TEXT NOT NULL DEFAULT '',
    role            TEXT,                     -- NULL — без роли
    status          TEXT NOT NULL DEFAULT 'created'
                    CHECK (status IN ('created', 'active', 'blocked')),
    is_local_admin  INTEGER NOT NULL DEFAULT 0,
    password_hash   TEXT,                     -- только у admin
    created_at      TEXT NOT NULL,
    last_login_at   TEXT
);

CREATE TABLE sessions (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash        TEXT NOT NULL UNIQUE,
    csrf_token        TEXT NOT NULL,
    created_at        TEXT NOT NULL,
    last_activity_at  TEXT NOT NULL,
    ip                TEXT NOT NULL DEFAULT '',
    user_agent        TEXT NOT NULL DEFAULT ''
);

CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE audit_log (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at              TEXT NOT NULL,
    actor_user_id   INTEGER,                  -- NULL — до входа (отказ, неудачная попытка)
    actor           TEXT NOT NULL DEFAULT '', -- имя на момент события
    ip              TEXT NOT NULL DEFAULT '',
    action          TEXT NOT NULL,
    target          TEXT NOT NULL DEFAULT '',
    old_value       TEXT,
    new_value       TEXT
);

CREATE INDEX idx_audit_action_ip_at ON audit_log(action, ip, at);

CREATE TABLE settings (
    key             TEXT PRIMARY KEY,
    value           TEXT NOT NULL,            -- JSON
    is_secret       INTEGER NOT NULL DEFAULT 0,
    updated_at      TEXT NOT NULL,
    updated_by      TEXT
);

-- Ключи приложения (подпись cookie состояния OAuth): переживают перезапуск и выкладку.
CREATE TABLE app_keys (
    name            TEXT PRIMARY KEY,
    value           TEXT NOT NULL,
    created_at      TEXT NOT NULL
);

-- Данные дашборда: те же документы, что были в базе артефакта (claude.use("db")):
-- коллекции state, nzp, nzd, brk, wk, rsu, msd (dashboard-status.md, «Данные в базе»).
-- seq — сквозной номер правки: страница забирает всё, что изменилось после её последнего seq.
-- Удалённый документ остаётся строкой с deleted = TRUE, чтобы удаление дошло до открытых страниц.
CREATE SEQUENCE documents_seq;

CREATE TABLE documents (
    collection      TEXT NOT NULL,
    doc_id          TEXT NOT NULL,
    data            JSONB,                    -- NULL у удалённого
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    seq             BIGINT NOT NULL,
    version         INTEGER NOT NULL DEFAULT 1,
    updated_at      TEXT NOT NULL,
    updated_by      TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (collection, doc_id)
);

CREATE INDEX idx_documents_seq ON documents(seq);
